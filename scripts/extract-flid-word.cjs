// Writes the outlines of "flid" in Geist weight 500 (the site's wordmark) for the 3D word.
const fontkit=require("fontkit"), wawoff=require("wawoff2"), fs=require("fs");
(async()=>{
const [,, src, out]=process.argv;
const ttf=Buffer.from(await wawoff.decompress(fs.readFileSync(src)));
const font=fontkit.create(ttf).getVariation({wght:500});
const upm=font.unitsPerEm, track=-0.07;
let x=0; const letters=[];
const r=(v)=>Math.round(v/upm*10000)/10000;
for (const ch of "flid") {
  const g=font.glyphForCodePoint(ch.codePointAt(0));
  letters.push({ch, x:Math.round(x*10000)/10000, path:g.path.commands.map(c=>[c.command,...c.args.map(r)])});
  x+=g.advanceWidth/upm+track;
}
const width=Math.round((x-track)*10000)/10000;
fs.writeFileSync(out,`// Outlines of "flid" taken from Geist-Variable.woff2 at weight 500, with the wordmark's -0.07em tracking.\n// Units are ems. Generated by lab/extract-flid-word.cjs; do not edit by hand.\nexport const FLID_WORD = ${JSON.stringify({width,letters})};\n`);
console.log(width,letters.map(l=>l.ch+":"+l.path.length+":"+[...new Set(l.path.map(p=>p[0]))].join("/")).join(" "));
})();
